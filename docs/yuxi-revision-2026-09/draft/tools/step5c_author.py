def rng(bs):
    bs = sorted(bs); out = []; s = p = bs[0]
    for x in bs[1:]:
        if x == p + 1: p = x; continue
        out.append(f'{s}–{p}' if s != p else f'{s}'); s = p = x
    out.append(f'{s}–{p}' if s != p else f'{s}'); return '、'.join(out)
