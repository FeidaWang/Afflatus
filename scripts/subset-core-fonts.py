"""Emit complete text optical instances while preserving original source fonts.
All original characters and weight ranges remain available. Only the optical
size axis is instanced at 28, avoiding duplicate partial font loads.
"""
from pathlib import Path
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont
root=Path(__file__).resolve().parents[1]
faces=[]
for name,family,weight in [('anthropic-sans-roman','Anthropic Sans','300 800'),('newsreader-var','Newsreader','200 800')]:
    font=TTFont(root/f'public/assets/fonts/{name}.woff2')
    codes=set(font.getBestCmap())
    ranges=','.join(f'U+{cp:X}' for cp in sorted(codes))
    font=instantiateVariableFont(font,{'opsz':28},inplace=True)
    font.flavor='woff2'
    filename=name+'-core.woff2';font.save(root/'public/assets/fonts'/filename)
    check=TTFont(root/'public/assets/fonts'/filename)
    assert set(check.getBestCmap())==codes
    faces.append(f'@font-face{{font-family:"{family}";src:url("/assets/fonts/{filename}") format("woff2");font-style:normal;font-weight:{weight};font-display:optional;unicode-range:{ranges}}}')
    print(filename,(root/'public/assets/fonts'/filename).stat().st_size)
(root/'public/styles/core-fonts.css').write_text('/* Generated by scripts/subset-core-fonts.py. Complete glyph and weight coverage, text optical master 28. */\n'+'\n'.join(faces)+'\n')
