const MONTHS = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
function dateLabel(iso) {
  const [year, month, day] = iso.slice(0, 10).split('-').map(Number);
  return {
    iso: iso.slice(0, 10),
    label: day
      ? { en: `${day} ${MONTHS[month - 1]} ${year}`, zh: `${year} 年 ${month} 月 ${day} 日` }
      : { en: `${MONTHS[month - 1]} ${year}`, zh: `${year} 年 ${month} 月` },
  };
}
const readPublicJson = (path) => JSON.parse(readFileSync(resolve(ROOT, path), 'utf8'));
const newestEvent = (events) => events.reduce((newest, event) => (event.date > newest.date ? event : newest));

// "Latest" homepage cards: the dated facts each destination page itself shows.
function homeLatest() {
  // The observatory renders its newest snapshot, not public/sectors-data.json.
  const observatoryPath = routeSeoFacts.sectors.provenance[0].path;
  const observatory = readPublicJson(observatoryPath);
  const observatoryEvent = newestEvent(observatory.events);
  const signalEvent = newestEvent(readPublicJson('public/signal-events.json').events);
  const serial = novelBooks().find((entry) => entry.id === 'yuxi-gongci');
  // updateNote has no date field or English text; the month is parsed from the note when it names one.
  const serialMonth = serial.novel.updateNote.match(/(\d{4})年(\d{1,2})月/);
  return [
    {
      href: '/sectors.html',
      date: dateLabel(observatory.updated),
      title: observatoryEvent.title,
      summary: observatoryEvent.body,
    },
    {
      href: '/signal.html',
      date: dateLabel(signalEvent.date),
      title: signalEvent.name,
      summary: signalEvent.print,
    },
    {
      href: '/serial.html',
      date: serialMonth ? dateLabel(`${serialMonth[1]}-${serialMonth[2].padStart(2, '0')}`) : null,
      title: { en: serial.novel.title, zh: serial.novel.title },
      summary: {
        en: `Original fiction in Chinese, ${serial.chapterCount} chapters.`,
        zh: serial.novel.updateNote,
      },
    },
  ];
}

