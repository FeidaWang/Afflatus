/* Sitemap <lastmod> = the git modification date of each page's content file.
   CI and Vercel check out shallow clones, so the dates are computed by
   `--write` from full history and committed; a shallow `--check` reuses
   that file and only full-history checkouts verify it is current. */
const SITEMAP_DATES_PATH = 'src/config/sitemapDates.generated.json';
const git = (...args) => execFileSync('git', args, { cwd: ROOT, encoding: 'utf8' }).trim();
function isShallowClone() {
  try { return git('rev-parse', '--is-shallow-repository') !== 'false'; } catch { return true; }
}
function gitDate(paths) {
  // Uncommitted edits land in the commit that ships them, i.e. today.
  if (git('status', '--porcelain', '--', ...paths)) return new Date().toLocaleDateString('en-CA');
  return git('log', '-1', '--format=%cs', '--', ...paths) || null;
}
function contentDates() {
  const dates = {};
  for (const route of SITEMAP_ROUTES) {
    if (routeSeoFacts[route.id]?.dateModified) continue;
    const date = gitDate([route.file]);
    for (const locale of route.publishedLocales || SITE_LOCALES) dates[localizedRouteUrl(route, locale)] = date;
  }
  for (const entry of novelBooks()) {
    const date = gitDate([`public/novels/${entry.id}.json`]);
    const book = JSON.parse(readFileSync(resolve(ROOT, `public/novels/${entry.id}.json`), 'utf8'));
    for (const chapter of [null, ...(book.chapters || [])]) {
      dates[readerUrl({ bookId: entry.id, ...(chapter ? { chapterId: chapter.id } : {}) })] = date;
    }
  }
  for (const { page, source } of COURSE_PAGES) {
    for (const lang of SITE_LOCALES) dates[courseUrl(lang, page)] = gitDate([source(lang)]);
  }
  return dates;
}

function generatedSitemap(dates) {
  const routeRows = SITEMAP_ROUTES.flatMap((route) => (
    (route.publishedLocales || SITE_LOCALES).map((locale) => {
    const url = localizedRouteUrl(route, locale);
    const lastModified = routeSeoFacts[route.id]?.dateModified?.slice(0, 10) || dates[url];
    const publishedLocales = route.publishedLocales || SITE_LOCALES;
    return [
      '  <url>',
      `    <loc>${url}</loc>`,
      ...(lastModified ? [`    <lastmod>${lastModified}</lastmod>`] : []),
      ...(publishedLocales.includes('en') ? [
        `    <xhtml:link rel="alternate" hreflang="en" href="${localizedRouteUrl(route, 'en')}"/>`,
      ] : []),
      `    <xhtml:link rel="alternate" hreflang="zh-CN" href="${localizedRouteUrl(route, 'zh')}"/>`,
      `    <xhtml:link rel="alternate" hreflang="x-default" href="${route.metadata.canonical}"/>`,
      '  </url>',
    ].join('\n');
  })));
  const courseRows = COURSE_PAGES.flatMap(({ page }) => SITE_LOCALES.map((lang) => [
    '  <url>',
    `    <loc>${courseUrl(lang, page)}</loc>`,
    ...(dates[courseUrl(lang, page)] ? [`    <lastmod>${dates[courseUrl(lang, page)]}</lastmod>`] : []),
    `    <xhtml:link rel="alternate" hreflang="en" href="${courseUrl('en', page)}"/>`,
    `    <xhtml:link rel="alternate" hreflang="zh-CN" href="${courseUrl('zh', page)}"/>`,
    `    <xhtml:link rel="alternate" hreflang="x-default" href="${courseUrl('en', page)}"/>`,
    '  </url>',
  ].join('\n')));
  const novelRows = novelBooks().flatMap((entry) => {
    const book = JSON.parse(readFileSync(resolve(ROOT, `public/novels/${entry.id}.json`), 'utf8'));
    return [null, ...(book.chapters || [])].flatMap((chapter) => (
      ['zh'].map((locale) => {
        const input = {
          bookId: entry.id,
          ...(chapter ? { chapterId: chapter.id } : {}),
        };
        const url = readerUrl({ ...input, locale });
        return [
          '  <url>',
          `    <loc>${url}</loc>`,
          ...(dates[url] ? [`    <lastmod>${dates[url]}</lastmod>`] : []),
          `    <xhtml:link rel="alternate" hreflang="zh-CN" href="${readerUrl({ ...input, locale: 'zh' })}"/>`,
          `    <xhtml:link rel="alternate" hreflang="x-default" href="${readerUrl({ ...input, locale: 'adaptive' })}"/>`,
          '  </url>',
        ].join('\n');
      })
    ));
  });
  return [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">',
    ...routeRows,
    ...courseRows,
    ...novelRows,
    '</urlset>',
    '',
  ].join('\n');
}

// A small publication projection: no prose rewrites, reader state or invented dates.
function generatedPublishedBooks() {
  const index = JSON.parse(readFileSync(resolve(ROOT, 'public/novels-index.json'), 'utf8'));
  const books = index.novels.map(entry => {
    const book = JSON.parse(readFileSync(resolve(ROOT, `public/novels/${entry.id}.json`), 'utf8'));
    const chapters = book.chapters || [];
    if (entry.chapterCount !== chapters.length) throw new Error(`${entry.id}: catalog/chapter count mismatch`);
    return { id: entry.id, title: entry.novel.title, author: entry.novel.author,
      chapterCount: chapters.length, firstChapterId: chapters[0]?.id ?? null,
      excerpt: chapters[0]?.blocks.find(block => block.type === 'p')?.text ?? null,
      source: `/novels/${entry.id}.json` };
  });
  return `// GENERATED by scripts/site-manifest.mjs from published novel files.\nexport const publishedBooks = ${JSON.stringify(books, null, 2)};\n`;
}

