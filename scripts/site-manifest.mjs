#!/usr/bin/env node
/**
 * Generate or verify site artifacts owned by src/config/siteManifest.js.
 *
 *   node scripts/site-manifest.mjs --write  # update generated artifacts
 *   node scripts/site-manifest.mjs --check  # fail on route/metadata drift
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import {
  NAV_ROUTES,
  SITE_LOCALES,
  SITE_MANIFEST,
  SITEMAP_ROUTES,
  findRouteByPath,
  localizedRouteUrl,
} from '../src/config/siteManifest.js';
import { readerUrl } from '../src/lib/serialRoutes.js';
import {
  buildRouteStructuredData,
  loadRouteSeoFacts,
  transformRouteSeoSource,
  validateRouteStructuredData,
} from './route-seo.mjs';

const ROOT = resolve(import.meta.dirname, '..');
const MODE = process.argv.includes('--write') ? 'write' : 'check';
const failures = [];
let localePrepaintBody = null;
const ACTIVE_ROUTES = SITE_MANIFEST.filter((route) => route.status === 'active');
const routeSeoFacts = await loadRouteSeoFacts(ROOT, ACTIVE_ROUTES);

function fail(message) {
  failures.push(message);
}

function generatedSitemap() {
  const routeRows = SITEMAP_ROUTES.flatMap((route) => (
    (route.publishedLocales || SITE_LOCALES).map((locale) => {
    const url = localizedRouteUrl(route, locale);
    const lastModified = routeSeoFacts[route.id]?.dateModified?.slice(0, 10);
    const publishedLocales = route.publishedLocales || SITE_LOCALES;
    return [
      '  <url>',
      `    <loc>${url}</loc>`,
      ...(lastModified ? [`    <lastmod>${lastModified}</lastmod>`] : []),
      ...(publishedLocales.includes('en') ? [
        `    <xhtml:link rel="alternate" hreflang="en" href="${localizedRouteUrl(route, 'en')}"/>`,
      ] : []),
      `    <xhtml:link rel="alternate" hreflang="zh-CN" href="${localizedRouteUrl(route, 'zh')}"/>`,
      `    <xhtml:link rel="alternate" hreflang="x-default" href="${route.metadata.canonical}"/>`,
      '  </url>',
    ].join('\n');
  })));
  const novelsIndex = JSON.parse(readFileSync(resolve(ROOT, 'public/novels-index.json'), 'utf8'));
  const novelRows = (novelsIndex.novels || []).flatMap((entry) => {
    const book = JSON.parse(readFileSync(resolve(ROOT, `public/novels/${entry.id}.json`), 'utf8'));
    return [null, ...(book.chapters || [])].flatMap((chapter) => (
      ['zh'].map((locale) => {
        const input = {
          bookId: entry.id,
          ...(chapter ? { chapterId: chapter.id } : {}),
        };
        return [
          '  <url>',
          `    <loc>${readerUrl({ ...input, locale })}</loc>`,
          `    <xhtml:link rel="alternate" hreflang="zh-CN" href="${readerUrl({ ...input, locale: 'zh' })}"/>`,
          `    <xhtml:link rel="alternate" hreflang="x-default" href="${readerUrl({ ...input, locale: 'adaptive' })}"/>`,
          '  </url>',
        ].join('\n');
      })
    ));
  });
  return [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">',
    ...routeRows,
    ...novelRows,
    '</urlset>',
    '',
  ].join('\n');
}

function generatedNavModule() {
  return [
    '// GENERATED by scripts/site-manifest.mjs — do not edit by hand.',
    '// Browser-safe projection of src/config/siteManifest.js.',
    '',
    `export const NAV_ROUTES = Object.freeze(${JSON.stringify(NAV_ROUTES, null, 2)});`,
    '',
    'export function normalizeRoutePath(pathname) {',
    "  const withoutLocale = String(pathname || '/').replace(/^\\/(?:en|zh)(?=\\/|$)/, '') || '/';",
    "  const path = withoutLocale.replace(/index\\.html$/, '');",
    "  return path === '' ? '/' : path;",
    '}',
    '',
  ].join('\n');
}

function generatedPerformanceRoutesModule() {
  const routes = SITE_MANIFEST
    .filter((route) => route.status === 'active')
    .map(({ id, path }) => ({ id, path }));

  return [
    '// GENERATED by scripts/site-manifest.mjs — do not edit by hand.',
    '// Minimal active-route projection for privacy-bounded performance telemetry.',
    '',
    `export const PERFORMANCE_ROUTES = Object.freeze(${JSON.stringify(routes, null, 2)});`,
    '',
    'export function normalizePerformancePath(pathname) {',
    "  const raw = String(pathname || '/').split(/[?#]/, 1)[0];",
    "  const withoutLocale = raw.replace(/^\\/(?:en|zh)(?=\\/|$)/, '') || '/';",
    "  const path = withoutLocale.replace(/\\/index\\.html$/, '/');",
    "  return path === '' ? '/' : path;",
    '}',
    '',
    'export function findPerformanceRoute(pathname) {',
    '  const normalized = normalizePerformancePath(pathname);',
    '  return PERFORMANCE_ROUTES.find((route) => route.path === normalized) || null;',
    '}',
    '',
  ].join('\n');
}

function generatedLighthouseRoutes() {
  const routes = SITE_MANIFEST
    .filter((route) => route.status === 'active')
    .map(({ id, path }) => ({ id, path }));
  return `${JSON.stringify({ schemaVersion: 1, routes }, null, 2)}\n`;
}

function parseAttributes(tag) {
  const attrs = {};
  const pattern = /([:\w-]+)\s*=\s*(?:"([^"]*)"|'([^']*)')/g;
  for (const match of tag.matchAll(pattern)) {
    attrs[match[1].toLowerCase()] = (match[2] ?? match[3] ?? '')
      .replaceAll('&quot;', '"')
      .replaceAll('&#39;', "'")
      .replaceAll('&lt;', '<')
      .replaceAll('&gt;', '>')
      .replaceAll('&amp;', '&');
  }
  return attrs;
}

function findTagByAttribute(html, tagName, attribute, value) {
  const tags = html.match(new RegExp(`<${tagName}\\b[^>]*>`, 'gi')) || [];
  for (const tag of tags) {
    const attrs = parseAttributes(tag);
    if (attrs[attribute] === value) return attrs;
  }
  return null;
}

function readTitle(html) {
  return html.match(/<title>([\s\S]*?)<\/title>/i)?.[1]?.trim() || null;
}

function readMeta(html, name) {
  return findTagByAttribute(html, 'meta', 'name', name)?.content ?? null;
}

function readOg(html, property) {
  return findTagByAttribute(html, 'meta', 'property', property)?.content ?? null;
}

function readCanonical(html) {
  return findTagByAttribute(html, 'link', 'rel', 'canonical')?.href ?? null;
}

function expectEqual(route, field, actual, expected) {
  if (actual !== expected) {
    fail(`${route.file}: ${field} is ${JSON.stringify(actual)}, manifest expects ${JSON.stringify(expected)}`);
  }
}

function auditRoute(route) {
  const path = resolve(ROOT, route.file);
  if (!existsSync(path)) {
    fail(`${route.id}: missing route file ${route.file}`);
    return;
  }

  const html = readFileSync(path, 'utf8');
  expectEqual(route, 'title', readTitle(html), route.metadata.title);
  expectEqual(route, 'theme-color', readMeta(html, 'theme-color'), route.themeColor);
  const viewport = readMeta(html, 'viewport') || '';
  if (!/(?:^|,\s*)viewport-fit=cover(?:\s*,|$)/i.test(viewport)) {
    fail(`${route.file}: viewport metadata must include viewport-fit=cover`);
  }

  const responsiveStyles = html.match(
    /<link\b[^>]*href=["']\/styles\/responsive-primitives\.css["'][^>]*>/gi,
  ) || [];
  if (responsiveStyles.length !== 1) {
    fail(
      `${route.file}: must load /styles/responsive-primitives.css exactly once (found ${responsiveStyles.length})`,
    );
  }

  if (route.metadata.description != null) {
    expectEqual(route, 'description', readMeta(html, 'description'), route.metadata.description);
  }
  if (route.metadata.canonical != null) {
    expectEqual(route, 'canonical', readCanonical(html), route.metadata.canonical);
  }
  if (route.metadata.ogTitle != null) {
    expectEqual(route, 'og:title', readOg(html, 'og:title'), route.metadata.ogTitle);
  }
  if (route.metadata.ogDescription != null) {
    expectEqual(route, 'og:description', readOg(html, 'og:description'), route.metadata.ogDescription);
  }
  if (route.metadata.ogImage != null) {
    expectEqual(route, 'og:image', readOg(html, 'og:image'), route.metadata.ogImage);
  }
  if (route.metadata.robots != null) {
    expectEqual(route, 'robots', readMeta(html, 'robots'), route.metadata.robots);
  }

  if (route.status === 'active' && !/<h1(?:\s|>)/i.test(html)) {
    fail(`${route.file}: active route must contain an h1`);
  }

  if (route.status === 'active') {
    const graph = buildRouteStructuredData(route, {
      facts: routeSeoFacts[route.id],
    });
    for (const message of validateRouteStructuredData(route, graph)) {
      fail(message);
    }

    const performanceEntries = html.match(
      /<script\s+type=["']module["']\s+src=["']\/src\/entry\/performance\.js["']\s*><\/script>/gi,
    ) || [];
    if (performanceEntries.length !== 1) {
      fail(
        `${route.file}: active route must load /src/entry/performance.js exactly once (found ${performanceEntries.length})`,
      );
    }
  }

  if (route.build) {
    const viewportEntries = html.match(
      /<script\s+type=["']module["']\s+src=["']\/src\/entry\/viewport\.js["']\s*><\/script>/gi,
    ) || [];
    if (viewportEntries.length !== 1) {
      fail(
        `${route.file}: built route must load /src/entry/viewport.js exactly once (found ${viewportEntries.length})`,
      );
    }
  }

  if (route.build && route.status !== 'prototype' && route.id !== 'serial') {
    const prepaint = html.match(/<script>([^<]*afflatus:locale:v1[^<]*)<\/script>/i)?.[1] || null;
    if (!prepaint) {
      fail(`${route.file}: missing synchronous locale pre-paint/migration script`);
    } else if (localePrepaintBody == null) {
      localePrepaintBody = prepaint;
    } else if (prepaint !== localePrepaintBody) {
      fail(`${route.file}: locale pre-paint script differs from other routes`);
    }
  }
}

function syncRouteSeo(route) {
  if (route.status !== 'active') return;
  const sourcePath = resolve(ROOT, route.file);
  if (!existsSync(sourcePath)) return;
  const source = readFileSync(sourcePath, 'utf8');
  const expected = transformRouteSeoSource(source, route, {
    facts: routeSeoFacts[route.id],
  });
  if (source === expected) return;

  if (MODE === 'write') {
    writeFileSync(sourcePath, expected);
    console.log(`UPDATED: ${route.file} route SEO`);
  } else {
    fail(`${route.file}: route SEO differs from siteManifest.js; run "npm run site:generate"`);
  }
}

function auditRedirects() {
  const vercelPath = resolve(ROOT, 'vercel.json');
  const config = JSON.parse(readFileSync(vercelPath, 'utf8'));
  const redirects = config.redirects || [];

  for (const route of SITE_MANIFEST.filter((item) => item.status === 'redirect')) {
    const redirect = redirects.find((item) => item.source === route.path);
    if (!redirect) {
      fail(`vercel.json: missing redirect for ${route.path}`);
      continue;
    }
    if (redirect.destination !== route.redirectTo) {
      fail(`vercel.json: ${route.path} redirects to ${redirect.destination}, expected ${route.redirectTo}`);
    }
    if (Boolean(redirect.permanent) !== Boolean(route.redirectPermanent)) {
      fail(`vercel.json: ${route.path} permanent=${redirect.permanent}, expected ${route.redirectPermanent}`);
    }
    if (findRouteByPath(route.redirectTo)?.status !== 'active') {
      fail(`${route.id}: redirect target ${route.redirectTo} is not active`);
    }
  }
}

function syncGeneratedFile(relativePath, expected) {
  const outputPath = resolve(ROOT, relativePath);
  const actual = existsSync(outputPath) ? readFileSync(outputPath, 'utf8') : '';
  if (MODE === 'write') {
    if (actual !== expected) {
      writeFileSync(outputPath, expected);
      console.log(`UPDATED: ${relativePath}`);
    } else {
      console.log(`OK: ${relativePath} already current`);
    }
  } else if (actual !== expected) {
    fail(`${relativePath} differs from siteManifest.js; run "npm run site:generate"`);
  }
}

for (const route of SITE_MANIFEST) syncRouteSeo(route);
for (const route of SITE_MANIFEST) auditRoute(route);
auditRedirects();
syncGeneratedFile('public/sitemap.xml', generatedSitemap());
syncGeneratedFile('src/config/navRoutes.generated.js', generatedNavModule());
syncGeneratedFile('src/config/performanceRoutes.generated.js', generatedPerformanceRoutesModule());
syncGeneratedFile('src/config/lighthouseRoutes.generated.json', generatedLighthouseRoutes());

if (failures.length) {
  for (const message of failures) console.error(`FAIL: ${message}`);
  process.exit(1);
}

console.log(`OK: site manifest (${SITE_MANIFEST.length} routes, ${SITEMAP_ROUTES.length} discoverable)`);
