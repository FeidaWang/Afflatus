"""Reproduce the small lab UI font from the preserved OFL reading font.
Run with fonttools[woff]; the original remains the fallback for novel text.
"""
from pathlib import Path
from fontTools import subset
from fontTools.ttLib import TTFont
root = Path(__file__).resolve().parents[1]
files = [root/'serial.html', root/'horoscope.html', root/'src/lib/dailyJournal.js']
import json
chars = set(''.join(p.read_text() for p in files))
for item in json.loads((root/'public/novels-index.json').read_text())['novels']:
    meta=item.get('novel',item)
    for field in ('title','subtitle','author'):
        chars.update(str(meta.get(field, '')))

font = TTFont(root/'public/assets/fonts/labs-serif-regular.woff2')
common = set(font.getBestCmap()) & {ord(c) for c in chars}
faces=[]
for label,codes in [('latin',{cp for cp in common if cp<0x2E80}),('cjk',{cp for cp in common if cp>=0x2E80})]:
    font=TTFont(root/'public/assets/fonts/labs-serif-regular.woff2')
    options=subset.Options();options.flavor='woff2'
    task=subset.Subsetter(options=options);task.populate(unicodes=codes);task.subset(font)
    filename=f'labs-serif-ui-{label}.woff2';font.save(root/'public/assets/fonts'/filename)
    ranges=','.join(f'U+{cp:X}' for cp in sorted(codes))
    faces.append(f"@font-face{{font-family:'Lab UI Serif';src:url('/assets/fonts/{filename}') format('woff2');font-display:optional;unicode-range:{ranges}}}")
    print(filename,len(codes),(root/'public/assets/fonts'/filename).stat().st_size)
css="/* Noto Serif SC / OFL. Generated by scripts/subset-labs-font.py. */\n@font-face{font-family:'Reader Serif';src:url('/assets/fonts/labs-serif-regular.woff2') format('woff2');font-display:optional}\n"+'\n'.join(faces)+'\n'
(root/'public/styles/labs-ui-font.css').write_text(css)

# The library shelf uses only its introductory copy and published book names.
# Keep the broad UI face as a fallback for dialogs and the observatory.
import re, html
source=(root/'serial.html').read_text()
from html.parser import HTMLParser
class LibraryCopy(HTMLParser):
    def __init__(self):
        super().__init__(); self.stack=[]; self.text=[]
    def handle_starttag(self, tag, attrs):
        attrs=dict(attrs)
        selected=(self.stack and self.stack[-1][1]) or tag in {'h2','h3'} or bool(set(attrs.get('class','').split()) & {'library-intro','continue-reading','shelf-heading','foot','toc-title'})
        if selected:
            self.text.extend(attrs.get(k,'') for k in ('data-en','data-zh'))
        if tag not in {'img','input','br','hr','link','meta','source','wbr','area','base','embed','param','track'}:
            self.stack.append((tag,selected))
    def handle_endtag(self, tag):
        for i in range(len(self.stack)-1,-1,-1):
            if self.stack[i][0]==tag:
                self.stack=self.stack[:i]; break
    def handle_data(self, data):
        if self.stack and self.stack[-1][1]: self.text.append(data)
copy=LibraryCopy(); copy.feed(source)
library=''.join(copy.text)
for item in json.loads((root/'public/novels-index.json').read_text())['novels']:
    meta=item.get('novel',item)
    library+=str(meta.get('title',''))
font=TTFont(root/'public/assets/fonts/labs-serif-regular.woff2')
codes=set(font.getBestCmap()) & {ord(c) for c in library}
options=subset.Options();options.flavor='woff2'
task=subset.Subsetter(options=options);task.populate(unicodes=codes);task.subset(font)
font.save(root/'public/assets/fonts/library-serif.woff2')
ranges=','.join(f'U+{cp:X}' for cp in sorted(codes))
with (root/'public/styles/labs-ui-font.css').open('a') as out:
    out.write(f"@font-face{{font-family:'Library Serif';src:url('/assets/fonts/library-serif.woff2') format('woff2');font-display:optional;unicode-range:{ranges}}}\n")
print('Library glyphs',len(codes),'bytes',(root/'public/assets/fonts/library-serif.woff2').stat().st_size)
