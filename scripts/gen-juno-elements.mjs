#!/usr/bin/env node
/* gen-juno-elements.mjs — builds src/lib/junoElements.js, a table of
 * osculating heliocentric orbital elements of 3 Juno (婚神星) every 2 years
 * 1898–2102. A single element set drifts by several degrees over decades
 * (Jupiter perturbations), so the runtime uses the set nearest the chart
 * date (≤1 yr of pure Kepler propagation → ~0.02°).
 *
 * Seed: JPL SBDB osculating elements, epoch JD 2461200.5 TDB (2026-06-09),
 * solution 2026-06-05 (DE441), heliocentric ecliptic J2000:
 *   https://ssd-api.jpl.nasa.gov/sbdb.api?sstr=3&full-prec=1
 * The seed state is integrated backwards/forwards with astronomy-engine's
 * GravitySimulator (Sun + Jupiter/Saturn/Uranus/Neptune) at 1-day steps,
 * and osculating elements are sampled every 730.5 days.
 * Verified against JPL Horizons apparent ecliptic longitudes (see
 * tests/westernPro.test.js). Run: node scripts/gen-juno-elements.mjs */
import * as A from 'astronomy-engine';
import { writeFileSync } from 'node:fs';

const DEG = Math.PI / 180, K = 0.01720209895, GM = K * K; // AU^3/day^2
const EPS = 23.4392911 * DEG;
const SEED = { jd: 2461200.5, a: 2.670989527103278, e: 0.2556999836681878, i: 12.98659236598085, node: 169.8115953492418, peri: 247.8950743075613, M: 262.7322944883855 };

function elementsToState(el) {
  const { a, e } = el; const i = el.i * DEG, O = el.node * DEG, w = el.peri * DEG;
  let E = el.M * DEG; for (let k = 0; k < 50; k++) E -= (E - e * Math.sin(E) - el.M * DEG) / (1 - e * Math.cos(E));
  const n = Math.sqrt(GM / (a * a * a));
  const xp = a * (Math.cos(E) - e), yp = a * Math.sqrt(1 - e * e) * Math.sin(E);
  const r = a * (1 - e * Math.cos(E));
  const vxp = -a * n * Math.sin(E) / (1 - e * Math.cos(E)), vyp = a * n * Math.sqrt(1 - e * e) * Math.cos(E) / (1 - e * Math.cos(E));
  const rot = (x, y) => {
    const cO = Math.cos(O), sO = Math.sin(O), cw = Math.cos(w), sw = Math.sin(w), ci = Math.cos(i), si = Math.sin(i);
    return [
      (cO * cw - sO * sw * ci) * x + (-cO * sw - sO * cw * ci) * y,
      (sO * cw + cO * sw * ci) * x + (-sO * sw + cO * cw * ci) * y,
      (sw * si) * x + (cw * si) * y,
    ];
  };
  const toEq = ([x, y, z]) => [x, y * Math.cos(EPS) - z * Math.sin(EPS), y * Math.sin(EPS) + z * Math.cos(EPS)];
  return { p: toEq(rot(xp, yp)), v: toEq(rot(vxp, vyp)), r };
}
function stateToElements(p, v) {
  const fromEq = ([x, y, z]) => [x, y * Math.cos(EPS) + z * Math.sin(EPS), -y * Math.sin(EPS) + z * Math.cos(EPS)];
  const r = fromEq(p), vv = fromEq(v);
  const rn = Math.hypot(...r), v2 = vv[0] ** 2 + vv[1] ** 2 + vv[2] ** 2;
  const h = [r[1] * vv[2] - r[2] * vv[1], r[2] * vv[0] - r[0] * vv[2], r[0] * vv[1] - r[1] * vv[0]];
  const hn = Math.hypot(...h);
  const a = 1 / (2 / rn - v2 / GM);
  const ev = [0, 1, 2].map((k) => ((v2 - GM / rn) * r[k] - (r[0] * vv[0] + r[1] * vv[1] + r[2] * vv[2]) * vv[k]) / GM);
  const e = Math.hypot(...ev);
  const i = Math.acos(h[2] / hn);
  const node = Math.atan2(h[0], -h[1]);
  const nvec = [Math.cos(node), Math.sin(node), 0];
  let peri = Math.acos((nvec[0] * ev[0] + nvec[1] * ev[1]) / e); if (ev[2] < 0) peri = 2 * Math.PI - peri;
  let nu = Math.acos((ev[0] * r[0] + ev[1] * r[1] + ev[2] * r[2]) / (e * rn)); if (r[0] * vv[0] + r[1] * vv[1] + r[2] * vv[2] < 0) nu = 2 * Math.PI - nu;
  const E = 2 * Math.atan2(Math.sqrt(1 - e) * Math.sin(nu / 2), Math.sqrt(1 + e) * Math.cos(nu / 2));
  const M = E - e * Math.sin(E);
  const n360 = (x) => ((x / DEG) % 360 + 360) % 360;
  return { a, e, i: i / DEG, node: n360(node), peri: n360(peri), M: n360(M) };
}

const jdToDate = (jd) => new Date((jd - 2440587.5) * 864e5);
const s0 = elementsToState(SEED);
const t0 = A.MakeTime(jdToDate(SEED.jd));
const rows = new Map();
for (const dir of [-1, 1]) {
  const sim = new A.GravitySimulator(A.Body.Sun, t0, [new A.StateVector(...s0.p, ...s0.v, t0)]);
  const epochs = [];
  for (let jd = 2415020.5 - 731; jd <= 2488069.5 + 731; jd += 730.5) epochs.push(jd);
  epochs.sort((x, y) => dir * (x - y));
  let jd = SEED.jd;
  for (const target of epochs) {
    if (dir * (target - SEED.jd) < 0) continue;
    while (dir * (target - jd) > 0) { jd = dir > 0 ? Math.min(jd + 1, target) : Math.max(jd - 1, target); sim.Update(A.MakeTime(jdToDate(jd))); }
    const [st] = sim.Update(A.MakeTime(jdToDate(jd)));
    rows.set(target, stateToElements([st.x, st.y, st.z], [st.vx, st.vy, st.vz]));
  }
}
const list = [...rows.entries()].sort((a, b) => a[0] - b[0]);
const f = (x, d) => Number(x.toFixed(d));
const body = list.map(([jd, e]) => `  [${jd}, ${f(e.a, 9)}, ${f(e.e, 9)}, ${f(e.i, 7)}, ${f(e.node, 7)}, ${f(e.peri, 7)}, ${f(e.M, 7)}],`).join('\n');
writeFileSync(new URL('../src/lib/junoElements.js', import.meta.url), `/* GENERATED by scripts/gen-juno-elements.mjs — do not edit by hand.
   Osculating heliocentric elements of 3 Juno, ecliptic & equinox J2000,
   every 730.5 days. Columns: [epoch JD (TT), a (AU), e, i°, Ω°, ω°, M°].
   Seed: JPL SBDB (DE441 solution 2026-06-05), integrated with
   astronomy-engine's GravitySimulator. */
export const JUNO_ELEMENTS = [
${body}
];
`);
