def main():
    print("Loading novel...")
    with open(NOVEL_PATH, "r", encoding="utf-8") as f:
        novel = json.load(f)

    ch44 = novel["chapters"][43]
    print(f"Chapter 44 before: {len(ch44['blocks'])} blocks, wordCount={ch44['wordCount']}")

    # Append new blocks
    ch44['blocks'].extend(NEW_BLOCKS)
    new_text = "".join(b["text"] for b in ch44["blocks"])
    ch44['wordCount'] = clean_len(new_text)

    print(f"Chapter 44 after: {len(ch44['blocks'])} blocks, wordCount={ch44['wordCount']}")

    # Recalculate totalWords
    novel["totalWords"] = sum(c["wordCount"] for c in novel["chapters"])
    print(f"Novel totalWords: {novel['totalWords']}")

    with open(NOVEL_PATH, "w", encoding="utf-8") as f:
        json.dump(novel, f, ensure_ascii=False, indent=2)

    print("Updated public/novels/yuxi-gongci.json successfully!")

if __name__ == "__main__":
    main()
