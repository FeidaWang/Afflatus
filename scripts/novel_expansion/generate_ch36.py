    total_vis = sum(len(re.sub(r'\s', '', b)) for b in blocks)
    print(f"Total visible characters for Chapter 36: {total_vis}")

    # Verify uniqueness against Ch 1-35
    with open('public/novels/yuxi-gongci.json', 'r', encoding='utf-8') as f:
        data = json.load(f)

    existing_texts = set()
    for ch in data['chapters'][:35]:
        for b in ch.get('blocks', []):
            t = b.get('text', '').strip()
            if t:
                existing_texts.add(t)

    duplicates = [b for b in blocks if b.strip() in existing_texts]
    if duplicates:
        print(f"ERROR: {len(duplicates)} duplicates found with existing chapters!")
        for d in duplicates[:5]:
            print("Dup:", d[:60])
        return

    # Check internal duplicates
    if len(blocks) != len(set(blocks)):
        print("ERROR: Internal duplicates found within Chapter 36!")
        return

    print("SUCCESS: 0 duplicates found!")

    if total_vis < 10000:
        print(f"WARNING: Character count {total_vis} < 10,000! Needs more words!")
        return

    # Write Chapter 36 into public/novels/yuxi-gongci.json
    ch36 = data['chapters'][35]
    print(f"Updating Chapter 36: {ch36.get('title')}")
    ch36['blocks'] = [{'type': 'p', 'text': b} for b in blocks]
    ch36['wordCount'] = total_vis

    # Update totalWords
    data['totalWords'] = sum(c['wordCount'] for c in data['chapters'])
    print(f"New totalWords: {data['totalWords']}")

    with open('public/novels/yuxi-gongci.json', 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

    print("Successfully written Chapter 36 to public/novels/yuxi-gongci.json!")

